import {readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
const fail=s=>{throw Error('EUDA-2026-10-19: '+s)};
const must=(ok,s)=>{if(!ok)fail(s)};
const id='doc-eu-euda-2026-10-19-exo-fhp-pd-26-d-110';
const source='project-memory/documents-2026-supplement-2026-10-19-euda-reply.json';
const pub='web/documents/report-04082026-010/120-euda-exo-fhp-pd-26-d-110-2026-10-19-verejna-textova-kopie.pdf';
const manifest=JSON.parse(await readFile('project-memory/document-sources.json','utf8'));
const records=JSON.parse(await readFile(source,'utf8'));
must(manifest.sources.some(x=>x.path===source),'new supplement missing from manifest');
must(records.documents.length===1,'unexpected records');
const r=records.documents[0];
must(r.id===id&&r.issue_date==='2026-10-19'&&r.received_date===null,'date changed or receipt date invented');
must(r.institution_id==='EU-EUDA'&&r.reference==='EXO/FHP/pd (26) D 110','author/reference mismatch');
must(r.document_type==='state_record'&&r.submission_side==='incoming_from_state_or_public_institution','Godot incoming side missing');
must(r.relations.some(x=>x.target_id==='doc-en-dd-2026-09-26-slalom-augsep-082'),'missing original procedural objection link');
must(r.relations.some(x=>x.target_id==='doc-eu-euda-2026-09-25-exo-fhp-pd-26-d-106'),'missing preceding EUDA reply');
must(r.public?.pdf==='documents/report-04082026-010/120-euda-exo-fhp-pd-26-d-110-2026-10-19-verejna-textova-kopie.pdf','wrong public PDF path');
must(r.public?.verification_status.includes('not_byte_identical_original'),'false original status');
const bytes=await readFile(pub);
const digest=createHash('sha256').update(bytes).digest('hex');
must(bytes.subarray(0,5).toString()==='%PDF-'&&bytes.subarray(-4096).includes(Buffer.from('%%EOF')),'invalid PDF structure');
must(bytes.length>3000&&digest===r.public.sha256,'PDF missing or hash mismatched');
const info=execFileSync('pdfinfo',[pub],{encoding:'utf8'});
must(/Pages:\s+2\b/.test(info),'public copy is not 2 pages');
const text=execFileSync('pdftotext',['-layout',pub,'-'],{encoding:'utf8'});
const normalized=text.replace(/\s+/g,' ');
for(const term of ['EXO/FHP/pd (26) D 110','25 September 2026','Nor does the EUDA','validation by the Agency','2023/1322','Article 15','1049/2001','Fabian Pereyra'])
  must(normalized.includes(term),'letter contains no '+term);
for(const forbidden of ['DusanDvorak@seznam.cz','Ospělov 6'])
  must(!normalized.includes(forbidden),'private contact in public PDF: '+forbidden);
const translations=JSON.parse(await readFile('project-memory/english-godot-translations.json','utf8'));
must(translations.documents[id]?.includes('forensic laboratories'),'English chronology absent');
const czech=await readFile('web/zpravy/04082026-010.html','utf8');
const english=await readFile('web/news/04082026-010.html','utf8');
must(czech.includes('id="'+id+'"')&&english.includes('id="en-'+id+'"'),'CZ/EN Godot lacks EUDA entry');
must(czech.includes('120-euda-exo-fhp-pd-26-d-110-2026-10-19')&&english.includes('120-euda-exo-fhp-pd-26-d-110-2026-10-19'),'CZ/EN Godot PDF link missing');
console.log('EUDA-2026-10-19-PUBLIC-PDF-AND-CZ-EN-GODOT-OK:',digest);
