import {readFile,stat} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const must=(condition,msg)=>{if(!condition)throw Error('OKTE_RELEASE_FAIL '+msg)};
const readJson=async file=>JSON.parse(await readFile(file,'utf8'));
const annexRegistry=await readJson('project-memory/documents-2026-supplement-2026-11-05-okte-olomouc-attachments.json');
const parentRegistry=await readJson('project-memory/documents-2026-supplement-2026-11-02-late-october.json');
const manifest=await readJson('project-memory/binary-sources/manifest.json');
const canonical=await readJson('web/data/documents-2026.json');
const cs=await readFile('web/zpravy/04082026-010.html','utf8');
const en=await readFile('web/news/04082026-010.html','utf8');
const parentPage=await readFile('web/listiny/2026-11-02-evidence-krpm.html','utf8');
const parentId='doc-cz-pcr-krpo-2026-10-30-krpm-145410-2';
const annexes=annexRegistry.documents;
must(annexes.length===10,'must be exactly ten independent original report annexes');
must(new Set(annexes.map(a=>a.id)).size===10,'duplicate canonical IDs');
must(new Set(annexes.map(a=>a.reference)).size===10,'duplicate report reference numbers');
const parent=parentRegistry.documents.find(d=>d.id===parentId);
must(parent?.reference==='KRPM-145410-2/ČJ-2026-1400AP-106','wrong parent police reply');
const canonicalIds=new Set(canonical.documents.map(d=>d.id));
const sourceIds=new Set(annexes.map(a=>a.id));
const links=parent.relations?.filter(r=>r.type==='priloha'&&sourceIds.has(r.target_id))||[];
must(links.length===10,'parent must link all ten annexes');
let pages=0,bytes=0;
for(const a of annexes){
  must(a.document_type==='state_record_attachment','annex must not be a separate 2026 response '+a.id);
  must(a.issue_date<'2026-10-30','date of old expert report must not be conflated with 2026 police reply');
  must(a.relations.some(r=>r.type==='priloha_k'&&r.target_id===parentId),'missing reverse parent relation '+a.id);
  must(canonicalIds.has(a.id),'missing canonical annex '+a.id);
  must(a.public.pdf.startsWith('documents/okte-originaly-2026-10-30/'),'unexpected PDF path '+a.id);
  must(a.public.sha256===a.public.source_original_sha256,'not a byte-identical original '+a.id);
  const source='web/'+a.public.pdf;
  const data=await readFile(source);
  const st=await stat(source);
  const sha=createHash('sha256').update(data).digest('hex');
  must(st.size===a.public.source_original_size_bytes,'size mismatch '+source);
  must(sha===a.public.sha256,'source original SHA-256 mismatch '+source);
  must(data.subarray(0,5).toString()==='%PDF-','invalid PDF header '+source);
  must(data.subarray(-4096).includes(Buffer.from('%%EOF')),'missing PDF EOF '+source);
  must(manifest.files.some(f=>f.target===source&&f.sha256===sha&&f.chunks.length),'missing materialization source '+source);
  must(parentPage.includes(a.public.pdf)&&parentPage.includes(sha),'public parent page misses annex PDF or SHA '+a.id);
  must(!cs.includes('<tr id="'+a.id+'"')&&!en.includes('<tr id="en-'+a.id+'"'),'annex must not get a new Godot row '+a.id);
  pages+=a.public.source_original_page_count; bytes+=data.length;
}
must(pages===47,'total original page count must be 47');
must(bytes===8615220,'total original source bytes mismatch');
must((cs.match(/<tr id="doc-cz-pcr-krpo-2026-10-30-krpm-145410-2"/g)||[]).length===1,'one Czech parent Godot row');
must((en.match(/<tr id="en-doc-cz-pcr-krpo-2026-10-30-krpm-145410-2"/g)||[]).length===1,'one English parent Godot row');
must(cs.includes('10 původních příloh OKTE'),'Czech chronology lacks annex link');
must(en.includes('10 original OKTE annexes'),'English chronology lacks annex link');
must(parentPage.includes('40stránková autorská srovnávací analýza'),'comparative analysis link missing');
must(!parentPage.includes('attachments were not included in the upload'),'stale missing-attachments claim');
console.log('OKTE_RELEASE_SUCCESS: 10 official originals, 47 pages, '+bytes+' bytes; SHA-256, chronology CZ/EN and parent links verified.');
